	"${KERNEL_SOURCE}/scripts/config" --file "${CONFIG}" --disable "${symbol}"
done

"${KERNEL_SOURCE}/scripts/config" --file "${CONFIG}" --enable UNWINDER_ORC

make -s -C "${KERNEL_SOURCE}" O="${KERNEL_BUILD}" olddefconfig

for symbol in "${disabled[@]}"; do
	if grep -Eq "^CONFIG_${symbol}=(y|m)$" "${CONFIG}"; then
		printf 'failed to disable CONFIG_%s\n' "${symbol}" >&2
		exit 1
	fi
done

for symbol in NUMA_BALANCING_MT LRU_GEN SYSFS; do
	if ! grep -q "^CONFIG_${symbol}=y$" "${CONFIG}"; then
		printf 'required CONFIG_%s is not enabled\n' "${symbol}" >&2
		exit 1
	fi
done

printf 'production kernel config updated: %s\n' "${CONFIG}"
