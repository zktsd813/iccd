#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
KERNEL_SOURCE="${KERNEL_SOURCE:-${REPO_ROOT}/linux}"
KERNEL_BUILD="${KERNEL_BUILD:-${REPO_ROOT}/linux-global-build}"
CONFIG="${KERNEL_BUILD}/.config"

[[ -x "${KERNEL_SOURCE}/scripts/config" ]] || {
	printf 'missing kernel config tool: %s\n' "${KERNEL_SOURCE}/scripts/config" >&2
	exit 2
}
[[ -f "${CONFIG}" ]] || {
	printf 'missing kernel build config: %s\n' "${CONFIG}" >&2
	exit 2
}

