#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
EXP_ROOT="$(cd -- "${SCRIPT_DIR}/.." && pwd)"

RUN_ID="${RUN_ID:-$(date -u +%Y%m%dT%H%M%SZ)-vm32-local16-32-48}"
SESSION="${SESSION:-vm32-realworld-${RUN_ID}}"
RESULTS_ROOT="${RESULTS_ROOT:-${EXP_ROOT}/results}"
RUN_ROOT="${RUN_ROOT:-${RESULTS_ROOT}/${RUN_ID}}"
STATE_DIR="${RUN_ROOT}/state"
mkdir -p "${STATE_DIR}"

ENV_FILE="${STATE_DIR}/tmux.env"
{
  printf 'RUN_ID=%q\n' "${RUN_ID}"
  printf 'RESULTS_ROOT=%q\n' "${RESULTS_ROOT}"
  printf 'RUN_ROOT=%q\n' "${RUN_ROOT}"
  printf 'LOCAL_SIZES_GIB=%q\n' "${LOCAL_SIZES_GIB:-16 32 48}"
  printf 'CONFIGS=%q\n' "${CONFIGS:-migration_off tiering_0x2 tpp_0x4}"
  printf 'WORKLOADS=%q\n' "${WORKLOADS:-pr bc gups graph500 btree redis_uniform redis_ycsb_a faster_uniform faster_ycsb_a}"
  printf 'GAPBS_DATA_DISK=%q\n' "${GAPBS_DATA_DISK:-1}"
  printf 'GAPBS_DATA_DISK_IMAGE=%q\n' "${GAPBS_DATA_DISK_IMAGE:-}"
  printf 'GAPBS_DATA_DISK_SIZE=%q\n' "${GAPBS_DATA_DISK_SIZE:-80G}"
  printf 'GAPBS_DATA_DISK_DEVICE=%q\n' "${GAPBS_DATA_DISK_DEVICE:-/dev/vdb}"
  printf 'GAPBS_DATA_DISK_MOUNT=%q\n' "${GAPBS_DATA_DISK_MOUNT:-/mnt/data}"
  printf 'GAPBS_GRAPH_GUEST=%q\n' "${GAPBS_GRAPH_GUEST:-}"
  printf 'HOST_CPUS=%q\n' "${HOST_CPUS:-0-31}"
  printf 'GUEST_CPUS=%q\n' "${GUEST_CPUS:-32}"
  printf 'GUEST_NODE0_CPUS=%q\n' "${GUEST_NODE0_CPUS:-0-31}"
  printf 'FAST_HOST_NODE=%q\n' "${FAST_HOST_NODE:-0}"
  printf 'SLOW_HOST_NODE=%q\n' "${SLOW_HOST_NODE:-2}"
  printf 'ALL_LOCAL_FAST_MEM=%q\n' "${ALL_LOCAL_FAST_MEM:-152G}"
  printf 'ALL_LOCAL_SLOW_MEM=%q\n' "${ALL_LOCAL_SLOW_MEM:-4G}"
  printf 'ALL_SLOW_FAST_MEM=%q\n' "${ALL_SLOW_FAST_MEM:-4G}"
  printf 'ALL_SLOW_SLOW_MEM=%q\n' "${ALL_SLOW_SLOW_MEM:-152G}"
  printf 'ALL_LOCAL_FAST_HOST_NODE=%q\n' "${ALL_LOCAL_FAST_HOST_NODE:-0}"
  printf 'ALL_LOCAL_SLOW_HOST_NODE=%q\n' "${ALL_LOCAL_SLOW_HOST_NODE:-2}"
  printf 'ALL_SLOW_FAST_HOST_NODE=%q\n' "${ALL_SLOW_FAST_HOST_NODE:-0}"
  printf 'ALL_SLOW_SLOW_HOST_NODE=%q\n' "${ALL_SLOW_SLOW_HOST_NODE:-2}"
  printf 'MIGRATION_SLOW_MEM=%q\n' "${MIGRATION_SLOW_MEM:-128G}"
  printf 'ROOTFS_VIRTUAL_SIZE=%q\n' "${ROOTFS_VIRTUAL_SIZE:-120G}"
  printf 'OMP_THREADS=%q\n' "${OMP_THREADS:-32}"
  printf 'NUMA_SCAN_SIZE_MB=%q\n' "${NUMA_SCAN_SIZE_MB:-}"
  printf 'NUMA_SCAN_PERIOD_MIN_MS=%q\n' "${NUMA_SCAN_PERIOD_MIN_MS:-}"
  printf 'LOCAL_FAULT_RATE=%q\n' "${LOCAL_FAULT_RATE:-}"
  printf 'REMOTE_FAULT_RATE=%q\n' "${REMOTE_FAULT_RATE:-}"
  printf 'LOCAL_FAULT_SCAN_PERIOD_MS=%q\n' "${LOCAL_FAULT_SCAN_PERIOD_MS:-}"
  printf 'LOCAL_FAULT_SCAN_SIZE_MB=%q\n' "${LOCAL_FAULT_SCAN_SIZE_MB:-}"
  printf 'REMOTE_FAULT_SCAN_PERIOD_MS=%q\n' "${REMOTE_FAULT_SCAN_PERIOD_MS:-}"
  printf 'REMOTE_FAULT_SCAN_SIZE_MB=%q\n' "${REMOTE_FAULT_SCAN_SIZE_MB:-}"
  printf 'PR_TRIALS=%q\n' "${PR_TRIALS:-8}"
  printf 'BC_TRIALS=%q\n' "${BC_TRIALS:-8}"
  printf 'FORBID_HOST_NODE1=%q\n' "${FORBID_HOST_NODE1:-1}"
  printf 'FAULT_BUCKET_CONTROLLER_DIR=%q\n' "${FAULT_BUCKET_CONTROLLER_DIR:-/Serverless/iccd-git/design/fault_bucket_controller}"
  printf 'CONTROLLER_PORT=%q\n' "${CONTROLLER_PORT:-10165}"
  printf 'CONTROLLER_WINDOW_SEC=%q\n' "${CONTROLLER_WINDOW_SEC:-5}"
  printf 'CONTROLLER_LOCAL_RATE=%q\n' "${CONTROLLER_LOCAL_RATE:-5}"
  printf 'CONTROLLER_REMOTE_RATE=%q\n' "${CONTROLLER_REMOTE_RATE:-5}"
  printf 'CONTROLLER_LOCAL_FAULT_SCAN_PERIOD_MS=%q\n' "${CONTROLLER_LOCAL_FAULT_SCAN_PERIOD_MS:-1000}"
  printf 'CONTROLLER_LOCAL_FAULT_SCAN_SIZE_MB=%q\n' "${CONTROLLER_LOCAL_FAULT_SCAN_SIZE_MB:-256}"
  printf 'CONTROLLER_REMOTE_FAULT_SCAN_PERIOD_MS=%q\n' "${CONTROLLER_REMOTE_FAULT_SCAN_PERIOD_MS:-${CONTROLLER_LOCAL_FAULT_SCAN_PERIOD_MS:-1000}}"
  printf 'CONTROLLER_REMOTE_FAULT_SCAN_SIZE_MB=%q\n' "${CONTROLLER_REMOTE_FAULT_SCAN_SIZE_MB:-${CONTROLLER_LOCAL_FAULT_SCAN_SIZE_MB:-256}}"
  printf 'CONTROLLER_MIN_LOCAL_PAGES=%q\n' "${CONTROLLER_MIN_LOCAL_PAGES:-1024}"
  printf 'CONTROLLER_MIN_REMOTE_PAGES=%q\n' "${CONTROLLER_MIN_REMOTE_PAGES:-1024}"
  printf 'CONTROLLER_CONSECUTIVE_EFFECTIVE=%q\n' "${CONTROLLER_CONSECUTIVE_EFFECTIVE:-2}"
  printf 'CONTROLLER_CONSECUTIVE_NO_IMPROVE=%q\n' "${CONTROLLER_CONSECUTIVE_NO_IMPROVE:-2}"
  printf 'CONTROLLER_RESTART_REMOTE_SHARE_THRESHOLD=%q\n' "${CONTROLLER_RESTART_REMOTE_SHARE_THRESHOLD:-1.2}"
  printf 'CONTROLLER_CONSECUTIVE_RESTART=%q\n' "${CONTROLLER_CONSECUTIVE_RESTART:-2}"
  printf 'CONTROLLER_RESTART_GRACE_WINDOWS=%q\n' "${CONTROLLER_RESTART_GRACE_WINDOWS:-1}"
  printf 'CONTROLLER_NUMA_BALANCING_ON=%q\n' "${CONTROLLER_NUMA_BALANCING_ON:-2}"
  printf 'CONTROLLER_NUMA_BALANCING_OFF=%q\n' "${CONTROLLER_NUMA_BALANCING_OFF:-0}"
} > "${ENV_FILE}"

CMD="set -a; source $(printf '%q' "${ENV_FILE}"); set +a; exec $(printf '%q' "${SCRIPT_DIR}/run_vm_sweep_host.sh")"
tmux new-session -d -s "${SESSION}" -c "${EXP_ROOT}" "${CMD}"
printf 'session=%s\nrun_root=%s\nenv=%s\n' "${SESSION}" "${RUN_ROOT}" "${ENV_FILE}"
